// Writes src/lib/poster-qr.ts: the fridge poster's QR code (/poster) as a constant SVG string.
//
//   node scripts/poster-qr.ts
//
// The poster always links to the same URL, so its QR code never changes. Making one tries eight
// masks (about 3 ms of CPU), which a cold isolate on Workers Free can't spare, so the Worker
// ships the finished SVG instead of qrcode-generator. Run this again if the URL or the markup
// below changes; test/fun-poster.test.ts fails until the committed constant matches.

import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { html } from 'hono/html';
import qrcode from 'qrcode-generator';

/** Where the poster points: `https://${DOMAIN}` (test/fun-poster.test.ts checks they agree). */
export const POSTER_URL = 'https://iszacka.dad';

/** The QR code for `text` as an inline SVG: one path, horizontal runs merged, 4-module quiet zone. */
export function qrSvg(text: string, label: string): string {
	const qr = qrcode(0, 'M');
	qr.addData(text);
	qr.make();
	const n = qr.getModuleCount();
	const quiet = 4;
	let d = '';
	for (let row = 0; row < n; row++) {
		let col = 0;
		while (col < n) {
			if (!qr.isDark(row, col)) {
				col++;
				continue;
			}
			const start = col;
			while (col < n && qr.isDark(row, col)) col++;
			d += `M${start + quiet} ${row + quiet}h${col - start}v1h-${col - start}z`;
		}
	}
	const size = n + quiet * 2;
	return String(
		html`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" shape-rendering="crispEdges" role="img" aria-label="${label}"><title>${label}</title><rect width="${size}" height="${size}" fill="#fff"/><path fill="#111" d="${d}"/></svg>`,
	);
}

/** The poster's SVG: a QR code for POSTER_URL, labelled for screen readers. */
export function posterQrSvg(url: string = POSTER_URL): string {
	return qrSvg(url, `QR code linking to ${url}`);
}

/** A TypeScript string literal for `s` (single-quoted, the house style, when nothing needs escaping). */
function literal(s: string): string {
	return /['\\\n\r\u2028\u2029]/.test(s) ? JSON.stringify(s) : `'${s}'`;
}

/** The source of src/lib/poster-qr.ts. */
export function posterQrModule(url: string = POSTER_URL): string {
	return `// GENERATED by scripts/poster-qr.ts (node scripts/poster-qr.ts). Do not edit by hand.
// The fridge poster's QR code, made once at build time rather than on every cold isolate.

/** The URL the poster's QR code encodes. */
export const POSTER_QR_URL = ${literal(url)};

/** The QR code for POSTER_QR_URL as an inline SVG (one path, 4-module quiet zone). */
export const POSTER_QR_SVG =
	${literal(posterQrSvg(url))};
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'poster-qr.ts');
	writeFileSync(out, posterQrModule());
	console.log(`wrote ${out}`);
}
